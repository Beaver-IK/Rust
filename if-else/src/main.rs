/*🌑 Лунная экспедиция 🪤

Наш луноход может перемещаться в четырех направлениях (Север, Юг, Запад и Восток) и принимать команды:

    0 - продолжить движение.
    1 - повернуть налево.
    2 - повернуть направо.

Напишите программу, которая считывает исходное направление (строка) и команду (u8),
а затем выводит направление лунохода Направление лунохода после выполнения команды:
Север, Юг, Запад или Восток после выполнения считанной команды, как показано в примере.

Гарантируется, что исходное направление и команды корректны!*/


use std::io::stdin;


fn read() -> String {
    let mut input = String::new();
    stdin().read_line(&mut input).expect("Error 1");
    input.trim().to_string()
}

fn main() {
    let directions = ["Запад", "Север", "Восток", "Юг"];
    let current_dir= read();
    let command: u8 = read().parse().expect("Error 2");
    
    let mut index = directions.iter().position(|&x| x == current_dir).expect("Error 3");
    
    if command == 1 {
        // Поворот налево: индекс - 1 (с циклическим переходом)
        index = (index + 3) % 4;  // +3 это то же самое что -1 для 4 элементов
    } else if command == 2 {
        // Поворот направо: индекс + 1 (с циклическим переходом)
        index = (index + 1) % 4;
    }
    // command == 0: индекс не меняем
    
    println!("Направление лунохода после выполнения команды: {}", directions[index]);
}